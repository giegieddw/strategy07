    portfolio = load_portfolio()
    
    print("\n" + "=" * 60)
    print("  Strategy 07 虚拟盘 - 当前持仓")
    print("=" * 60)
    
    stats = portfolio.get("stats", {})
    total_trades = stats.get("total_trades", 0)
    win_trades = stats.get("win_trades", 0)
