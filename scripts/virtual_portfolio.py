def check_strategy_signal(kline_data, realtime_data):
    """
    检测策略07信号: 跳空低开 + 收阳线
    
    参数:
      kline_data: 最近30天K线数据
      realtime_data: 当日实时数据
    
    返回: dict 或 None
    """
    if len(kline_data) < 2:
        return None
    
    curr = kline_data[-1]   # 当日
    prev = kline_data[-2]   # 前日
    
    # 条件1: 跳空低开 ≥ 0.2%
    gap_pct = (curr["open"] - prev["close"]) / prev["close"]
    if gap_pct > -GAP_THRESHOLD:
        return None  # 没有跳空或跳空不够
    
    # 条件2: 收阳线 (收盘 > 开盘)
    if curr["close"] <= curr["open"]:
        return None  # 不是阳线
    
    # 计算信号强度
    reversal_pct = (curr["close"] - curr["open"]) / curr["open"] * 100  # 日内反弹幅度
    
    return {
        "date": curr["date"],
        "gap_pct": round(gap_pct * 100, 2),       # 跳空幅度(%)
        "reversal_pct": round(reversal_pct, 2),     # 日内反弹幅度(%)
        "open": curr["open"],
        "close": curr["close"],
        "prev_close": prev["close"],
        "high": curr["high"],
        "low": curr["low"],
    }


