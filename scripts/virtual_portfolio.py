def select_stocks(signals, portfolio):
    """
    从信号中选股
    
    规则:
    1. 过滤已持仓的
    2. 优先跳空幅度大 + 反弹力度强的
    3. 最多选到 MAX_HOLDINGS 只
    """
    # 已有持仓代码
    held_codes = {h["code"] for h in portfolio.get("holdings", [])}
    
    # 候选: 过滤已持仓
    candidates = [s for s in signals if s["code"] not in held_codes]
    
    # 打分排序: gap绝对值 + reversal幅度
    for c in candidates:
        c["score"] = abs(c["gap_pct"]) + c["reversal_pct"]
    
    candidates.sort(key=lambda x: x["score"], reverse=True)
    
    # 当前空位
    slots = MAX_HOLDINGS - len(portfolio.get("holdings", []))
    selected = candidates[:slots]
    
    return selected


