def check_holdings_via_kline(portfolio, date):
    """
    用K线数据检查持仓止损（双模式）
    
    模式 daily: 日线最低价检查
    模式 5min/15min: 分钟级K线逐根检查，精度更高
    
    逻辑：
    1. 对每只持仓，拉取买入日以来的日线K线
    2. 逐日检查日线最低价是否触及止损线（粗筛）
    3. 如果STOP_CHECK_MODE是分钟级，对触发日再用分钟K线精确定位
    4. 移动止损随价格上移
    
    这样模拟了真实的"盘中触发止损"效果
    """
    closed_today = []
    
    for h in list(portfolio["holdings"]):
        if h["status"] != "holding":
            continue
        
        symbol = h["symbol"]
        buy_date = h["buy_date"]
        current_stop = h["stop_loss"]
        
        # 拉取买入日以来的日线K线
        klines = fetch_kline(symbol, count=60)
        if len(klines) < 2:
            continue
        
        triggered = False
        
        for k in klines:
            if k["date"] <= buy_date:
                continue
            if k["date"] > date:        # 不检查未来日期，杜绝前瞻偏差
                continue
            
            # 先检查止损（用昨天的止损线，不用今天的收盘价）
            if k["low"] <= current_stop:
                # 止损触发!
                # 判断是否需要分钟级精确定位
                if STOP_CHECK_MODE in ("5min", "15min", "30min", "60min"):
                    # 分钟级精确定位: 找到具体哪根分钟K线触发
                    sell_price, sell_time = _check_minute_stop(
                        symbol, current_stop, k["date"], STOP_CHECK_MODE
                    )
                    if sell_price is None:
                        sell_price = current_stop
                        sell_time = k["date"]
                else:
                    sell_price = current_stop
                    sell_time = k["date"]
                
                h["status"] = "stopped"
                h["sell_date"] = sell_time
                h["sell_price"] = sell_price
                h["stop_loss_triggered"] = current_stop
                h["stop_mode"] = STOP_CHECK_MODE if STOP_CHECK_MODE in ("5min","15min","30min","60min") else "daily"
                h["profit_pct"] = round((sell_price / h["buy_price"] - 1) * 100, 2)
                h["profit_amount"] = round((sell_price - h["buy_price"]) * h["shares"], 2)
                portfolio["stats"]["total_trades"] += 1
                if h["profit_amount"] > 0:
                    portfolio["stats"]["win_trades"] += 1
                portfolio["stats"]["total_profit"] += h["profit_amount"]
                triggered = True
                closed_today.append(h)
                break
            
            # 收盘后更新移动止损: 如果当日收盘价创新高, 上移止损线(给明天用)
            if k["close"] > h["buy_price"]:
                new_stop = k["close"] * 0.99
                if new_stop > current_stop:
                    current_stop = round(new_stop, 2)
        
        # 检查是否持有超过20天未触发止损 —— 强制平仓
        if not triggered:
            # 找到截止日期当天的那根K线作为"最后一天"
            last_k = None
            for k in klines:
                if k["date"] <= date:
                    last_k = k
            if last_k and last_k["date"] > buy_date:
                days_held = 0
                for k in klines:
                    if k["date"] > buy_date and k["date"] <= date:
                        days_held += 1
                
                if days_held >= 20:
                    h["status"] = "timeout"
                    h["sell_date"] = last_k["date"]
                    h["sell_price"] = last_k["close"]
                    
                    profit_pct = (last_k["close"] - h["buy_price"]) / h["buy_price"] * 100
                    profit_amount = (last_k["close"] - h["buy_price"]) * h["shares"]
                    h["profit_pct"] = round(profit_pct, 2)
                    h["profit_amount"] = round(profit_amount, 2)
                    
                    portfolio["stats"]["total_profit"] += profit_amount
                    if profit_pct > 0:
                        portfolio["stats"]["win_trades"] += 1
                    
                    closed_today.append(h)
                    
                    trade = {
                        "date": last_k["date"],
                        "type": "TIMEOUT",
                        "code": h["code"],
                        "name": h["name"],
                        "price": last_k["close"],
                        "shares": h["shares"],
                        "amount": round(last_k["close"] * h["shares"], 2),
                        "profit_pct": round(profit_pct, 2),
                        "profit_amount": round(profit_amount, 2),
                        "reason": f"持有{days_held}天强制平仓",
                    }
                    log = load_trade_log()
                    log.append(trade)
                    save_trade_log(log)
                    
                    icon = "[+]" if profit_pct > 0 else "[-]"
                    print(f"  [TIME] 超时平仓 {h['name']}({h['code']}) 持有{days_held}天")
                    print(f"     买入: {h['buy_price']:.2f}, 卖出: {last_k['close']:.2f}")
                    print(f"     盈亏: {profit_pct:+.2f}% ({profit_amount:+.2f}元)")
    
    # 移动已平仓到closed列表
    for h in closed_today:
        portfolio["holdings"].remove(h)
        portfolio["closed"].append(h)
    
    return closed_today


def _check_minute_stop(symbol, stop_price, target_date, period="5"):
    """
    用分钟级K线精确定位止损触发时间和价格
    
    参数:
      symbol: 股票代码
      stop_price: 当前止损价
      target_date: 日线触发止损的日期 (如 "2026-06-01")
      period: 分钟K线周期
    
    返回: (卖出价, 卖出时间) 或 (None, None)
    
    逻辑: 遍历当日每根分钟K线，找到第一根最低价跌破止损线的
    """
    minute_klines = fetch_minute_kline(symbol, period=period, count=240)
    if not minute_klines:
        return None, None
    
    # 将 target_date 转为分钟K线的日期格式 (如 "20260601")
    target_date_compact = target_date.replace("-", "")
    
    for mk in minute_klines:
        # 只检查目标日期的K线
        if mk["date"] != target_date_compact:
            continue
        
        # 开盘集合竞价跳过（09:30之前）
        if mk["time"] < "0930":
            continue
        
        # 最低价跌破止损线 → 触发!
        if mk["low"] <= stop_price:
            return stop_price, mk["datetime"]
    
    return None, None


