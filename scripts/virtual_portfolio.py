def fetch_kline(symbol, count=30):
    """
    获取K线数据
    参数:
      symbol: 如 sh600519
      count: 获取天数
    返回: [{date, open, close, high, low, volume}, ...]
    """
    url = f"{KLINE_URL}?_var=kline_day&param={symbol},day,,,{count},qfq"
    try:
        req = urllib.request.Request(url, headers={
            "User-Agent": "Mozilla/5.0",
            "Referer": "https://gu.qq.com/"
        })
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = resp.read().decode('utf-8')
        
        # 解析返回数据 (格式: kline_day={"qfqday":[[...],...]})
        start = data.find('{')
        if start == -1:
            return []
        json_data = json.loads(data[start:])
        
        klines = []
        raw = json_data.get("data", {}).get(symbol, {}).get("qfqday", [])
        if not raw:
            raw = json_data.get("data", {}).get(symbol, {}).get("day", [])
        
        for row in raw:
            if len(row) < 6:
                continue
            klines.append({
                "date": row[0],
                "open": float(row[1]),
                "close": float(row[2]),
                "high": float(row[3]),
                "low": float(row[4]),
                "volume": float(row[5]),
            })
        return klines
    except Exception as e:
        print(f"  [WARN] 获取K线失败 {symbol}: {e}")
        return []


def fetch_minute_kline(symbol, period="5", count=240):
    """
    获取分钟级K线数据（用于更精细的止损检查）
    
    参数:
      symbol: 如 sh600519
      period: K线周期 "1"/"5"/"15"/"30"/"60" (分钟)
      count: 获取根数
    
    返回: [{date, time, open, close, high, low, volume}, ...]
    """
    url = f"{MINUTE_KLINE_URL}?_var=min_data&param={symbol},m{period},,,{count}"
    try:
        req = urllib.request.Request(url, headers={
            "User-Agent": "Mozilla/5.0",
            "Referer": "https://gu.qq.com/"
        })
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = resp.read().decode('utf-8')
        
        # 解析: min_data={"code":0,"data":{"sh600519":{"m5":[[...],...]}}}
        start = data.find('{')
        if start == -1:
            return []
        json_data = json.loads(data[start:])
        
        # 按period找数据key
        data_key = f"m{period}"
        raw = json_data.get("data", {}).get(symbol, {}).get(data_key, [])
        
        klines = []
        for row in raw:
            if len(row) < 6:
                continue
            # 分钟K线格式: ["202606011500", 开盘, 收盘, 最高, 最低, 成交量, {}, 换手率]
            date_str = row[0]
            klines.append({
                "datetime": date_str,  # 如 "202606011500"
                "date": date_str[:8] if len(date_str) >= 8 else date_str,
                "time": date_str[8:12] if len(date_str) >= 12 else "",
                "open": float(row[1]),
                "close": float(row[2]),
                "high": float(row[3]),
                "low": float(row[4]),
                "volume": float(row[5]),
            })
        return klines
    except Exception as e:
        print(f"  [WARN] 获取分钟K线失败 {symbol}: {e}")
        return []


def fetch_realtime(symbols):
    """
    获取实时行情 (用于当日收盘数据)
    symbols: ["sh600519", "sz000858", ...]
    返回: {symbol: {price, change_pct, turnover, volume, pe, market_cap}, ...}
    """
    if not symbols:
        return {}
    
    # 分批获取, 每批最多50个
    results = {}
    batch_size = 50
    
    for i in range(0, len(symbols), batch_size):
        batch = symbols[i:i+batch_size]
        url = QT_URL + ",".join(batch)
        try:
            req = urllib.request.Request(url, headers={
                "User-Agent": "Mozilla/5.0",
                "Referer": "https://gu.qq.com/"
            })
            with urllib.request.urlopen(req, timeout=10) as resp:
                raw = resp.read().decode('gbk')
            
            for line in raw.strip().split("\n"):
                if not line.strip():
                    continue
                line = line.strip()
                # 格式: v_sz000858="1~五粮液~000858~..."
                eq = line.find("=")
                if eq == -1:
                    continue
                
                # 提取symbol
                var_name = line[:eq]
                symbol = var_name.replace("v_", "")
                
                # 提取引号内容
                q1 = line.find('"', eq)
                q2 = line.find('"', q1 + 1)
                if q1 == -1 or q2 == -1:
                    continue
                content = line[q1+1:q2]
                parts = content.split("~")
                
                if len(parts) < 50:
                    continue
                
                try:
                    results[symbol] = {
                        "name": parts[1],
                        "code": parts[2],
                        "price": float(parts[3]) if parts[3] else 0,
                        "change_pct": float(parts[32]) if parts[32] else 0,
                        "high": float(parts[33]) if parts[33] else 0,
                        "low": float(parts[34]) if parts[34] else 0,
                        "open": float(parts[5]) if parts[5] else 0,
                        "volume": float(parts[6]) if parts[6] else 0,  # 手
                        "amount": float(parts[37]) if parts[37] else 0,  # 万元
                        "turnover": float(parts[38]) if parts[38] else 0,
                        "pe": float(parts[39]) if parts[39] else 0,
                        "market_cap": float(parts[45]) if parts[45] else 0,  # 亿
                        "prev_close": float(parts[4]) if parts[4] else 0,
                    }
                except (ValueError, IndexError):
                    continue
        except Exception as e:
            print(f"  [WARN] 获取实时行情失败: {e}")
        
        time.sleep(0.1)  # 避免频率过高
    
    return results


